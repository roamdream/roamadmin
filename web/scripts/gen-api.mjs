// 从后端 OpenAPI 规范（/api.json）自动生成 TypeScript 类型（src/api/types.ts）。
//
// 用法：npm run gen:api
//   - 优先向运行中的后端拉取最新规范（可用 RA_API_URL 覆盖地址）；
//   - 拉取失败则回退到仓库内缓存的 openapi.json；
//   - 新增/修改后端接口后，重新执行即可，前端类型自动同步。
import { writeFileSync, readFileSync, existsSync } from 'node:fs'

const OPENAPI_FILE = 'openapi.json'
const OUT_FILE = 'src/api/types.ts'

async function ensureSpec() {
  const url = process.env.RA_API_URL || 'http://127.0.0.1:8600/api.json'
  try {
    const res = await fetch(url)
    if (res.ok) {
      writeFileSync(OPENAPI_FILE, await res.text())
      console.log('[gen-api] fetched', url, '->', OPENAPI_FILE)
      return
    }
  } catch {
    // 后端未启动时回退缓存
  }
  if (existsSync(OPENAPI_FILE)) {
    console.log('[gen-api] using cached', OPENAPI_FILE)
    return
  }
  throw new Error('无法拉取 API 规范，且不存在缓存的 openapi.json（请先启动后端或手动放置 openapi.json）')
}

await ensureSpec()
const spec = JSON.parse(readFileSync(OPENAPI_FILE, 'utf8'))
const schemas = spec.components?.schemas || {}

// 命名：github.com.roamdream.roamadmin.modules.<mod>.api.<Name> -> <Name>
// 同名冲突时以模块名前缀区分（如 demo.CreateReq）。
function friendly(full) {
  const m = full.match(/modules\.([^.]+)\.api\.([^.]+)$/)
  return m ? { mod: m[1], name: m[2], full } : { mod: '', name: full.replace(/[^A-Za-z0-9_]/g, '_'), full }
}
const cap = (s) => (s ? s[0].toUpperCase() + s.slice(1) : s)

const entries = Object.keys(schemas).map(friendly)
const byName = new Map()
for (const e of entries) {
  if (!byName.has(e.name)) byName.set(e.name, [])
  byName.get(e.name).push(e)
}
const finalName = (e) => (byName.get(e.name).length > 1 ? cap(e.mod) + e.name : e.name)

const refs = new Map()
for (const e of entries) refs.set(e.full, finalName(e))

function tsType(schema) {
  if (!schema) return 'unknown'
  if (schema.$ref) return refs.get(schema.$ref.replace('#/components/schemas/', '')) || 'unknown'
  switch (schema.type) {
    case 'string':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'array':
      return `${tsType(schema.items)}[]`
    case 'object':
      return 'Record<string, unknown>'
    default:
      return 'unknown'
  }
}

const lines = [
  '// AUTO-GENERATED by scripts/gen-api.mjs — do not edit manually.',
  '// Regenerate: npm run gen:api',
  '',
]

for (const e of entries) {
  const s = schemas[e.full]
  if (!s || s.type !== 'object' || !s.properties) {
    lines.push(`export type ${finalName(e)} = ${tsType(s)}`)
    lines.push('')
    continue
  }
  const required = new Set(s.required || [])
  lines.push(`export interface ${finalName(e)} {`)
  for (const [prop, ps] of Object.entries(s.properties)) {
    const opt = required.has(prop) ? '' : '?'
    const desc = ps?.description ? ` // ${ps.description}` : ''
    lines.push(`  ${prop}${opt}: ${tsType(ps)}${desc}`)
  }
  lines.push('}')
  lines.push('')
}

writeFileSync(OUT_FILE, lines.join('\n'))
console.log('[gen-api] wrote', OUT_FILE, `(${entries.length} types)`)
